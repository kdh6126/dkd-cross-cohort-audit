def dataset_rows():
    """설명자료의 데이터셋 표. 저장소가 준 값만 씁니다."""
    if not os.path.exists(PROV):
        return []
    d = pd.read_csv(PROV, sep='\t')
    out = []
    for _, r in d.iterrows():
        acc = r['accession']
        # GEO 의 gpl 필드는 접두어 없이 번호만 준다(571). 사전 열쇠는 GPL571 이다.
        plats = [PLATFORM.get('GPL' + g.strip(), PLATFORM.get(g.strip(), g.strip()))
                 for g in str(r.get('platform', '')).split('/') if g.strip()]
        plat = plats[0] if len(plats) == 1 else (
            plats[0] + ' 외 %d종' % (len(plats) - 1) if plats else '')
        n = r.get('n_samples')
        n = '' if pd.isna(n) else str(int(float(n)))
        out.append([acc, ROLE.get(acc, ''), str(r.get('title', ''))[:78], plat, n,
                    str(r.get('citation', '')) if not pd.isna(r.get('citation')) else '논문 없음'])
    return out


def dataset_rows_geo():
    """GEO 전사체만. 21행을 한 장에 넣으면 슬라이드를 3인치 넘긴다."""
    return [r for r in dataset_rows() if r[0].startswith('GSE')]


def dataset_rows_mw():
    """Metabolomics Workbench 대사체만."""
    return [r for r in dataset_rows() if r[0].startswith('ST')]


